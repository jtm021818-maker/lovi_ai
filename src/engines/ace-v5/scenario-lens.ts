/**
 * 시나리오 렌즈 블록 반환. 의미 있는 시나리오일 때만 텍스트, 아니면 null.
 *
 * @param scenario 분류된 관계 시나리오 (StateAnalysis 결과)
 * @returns systemPrompt 말미에 붙일 렌즈 블록 또는 null
 */
export function getScenarioLens(scenario: RelationshipScenario | string | null | undefined): string | null {
  if (!scenario) return null;
  const lens = SCENARIO_LENS[scenario as RelationshipScenario];
  if (!lens) return null;

  return `\n\n## 🎯 이 상황의 상담 렌즈 (시나리오: ${scenario})
아래는 이 상황에서 루나가 잡아야 할 톤·전략 가이드야. phase 흐름은 그대로 타되, 이 렌즈로 톤을 조절해.
${lens}`;
}
